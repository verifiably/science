"""A statement's readable page, rendered from its JSON content and adding nothing to it."""
from __future__ import annotations

import json
import re
from collections.abc import Iterable, Mapping, Sequence

from beliefs.reservation import ROLES

__all__ = ["render_page"]

_MARKUP = re.compile(r"([\\`*_\[\]<>|&~#])")
_NONE = "none"


def _text(value: str) -> str:
    """Record text as one table cell or line: markup is shown, never interpreted."""
    parts = (_MARKUP.sub(r"\\\1", line) if line.isprintable() else _MARKUP.sub(r"\\\1", json.dumps(line)[1:-1])
             for line in value.split("\n"))
    return "<br>".join(parts)


def _code(value: str) -> str:
    """An address, digest or timestamp: text no markup character can appear in."""
    return f"`{value}`" if re.fullmatch(r"[A-Za-z0-9:./@+-]+", value) else _text(value)


def _unit(unit: Mapping[str, str]) -> str:
    if "term" in unit:
        return f"{_text(unit['sort'])} {_text(unit['term'])}"
    return f"{unit['start']} .. {unit['end']}"


def _units(units: Iterable[Mapping[str, str]]) -> str:
    return "<br>".join(_unit(unit) for unit in units) or _NONE


def _table(headings: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    lines = [f"| {' | '.join(headings)} |", f"|{' --- |' * len(headings)}"]
    lines += [f"| {' | '.join(row)} |" for row in rows]
    return lines


def _section(title: str, headings: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    return ["", f"## {title}", "", *(_table(headings, rows) if rows else ["None."])]


def _changed(groups: Iterable[Mapping]) -> str:
    return "<br>".join(f"{group['role']}: {'; '.join(_unit(unit) for unit in group['units'])}"
                       for group in groups) or _NONE


def _groups(groups: Sequence[Mapping]) -> list[str]:
    rows = [(group["role"], _units(group["units"]), _text(group.get("label", "")), _code(group.get("basis", "")))
            for role in ROLES for group in groups if group["role"] == role]
    counts = ", ".join(f"{sum(group['role'] == role for group in groups)} {role}" for role in ROLES)
    lines = _section("Groups", ("Role", "Units", "Label", "Basis"), rows)
    return [*lines[:3], f"{counts}.", "", *lines[3:]]


def _history(history: Sequence[Mapping]) -> list[str]:
    return _section(
        "History", ("Assigned at", "Rule version", "Groups removed", "Groups added", "Events added", "Events dropped",
                    "Address"),
        [(entry["assigned_at"], _text(entry["rule"]["version"]), _changed(entry["groups_removed"]),
          _changed(entry["groups_added"]), str(len(entry["events_added"])), str(len(entry["events_dropped"])),
          _code(entry["address"])) for entry in history])


def _events(events: Sequence[Mapping]) -> list[str]:
    return _section(
        "Considered exposure", ("Observed at", "Channel", "Class", "Effect", "Units", "Observer", "Account", "Address"),
        [(facet["observed_at"], facet["channel"], _text(facet["class"]), facet["effect"], _units(facet["units"]),
          _text(facet["observer"]), _text(facet["account"]), _code(event["address"]))
         for event in events for facet in (event["facet"],)])


def render_page(content: Mapping) -> str:
    facet = content["head"]["facet"]
    facts = [("Chain", _text(content["chain"]))]
    if "scope" in content:
        facts.append(("Scope", _code(content["scope"])))
    facts += [("Head", _code(content["head"]["address"])),
              ("Rule", f"{_text(facet['rule']['name'])}, version {_text(facet['rule']['version'])}"),
              ("Assigned", f"{facet['assigned_at']} by {_text(facet['assigned_by'])}")]
    lines = [
        "Generated by `science reservation-statement`; do not edit.",
        "",
        f"# Reservation: {_text(content['chain'])}",
        "",
        *(f"- {name}: {value}" for name, value in facts),
        *_section("Frozen inputs", ("Input", "Digest"),
                  [(_text(name), _code(digest)) for name, digest in sorted(facet["inputs"].items())]),
        *_groups(facet["groups"]),
        *_history(content["history"]),
        *_events(content["events"]),
    ]
    return "\n".join(lines) + "\n"
